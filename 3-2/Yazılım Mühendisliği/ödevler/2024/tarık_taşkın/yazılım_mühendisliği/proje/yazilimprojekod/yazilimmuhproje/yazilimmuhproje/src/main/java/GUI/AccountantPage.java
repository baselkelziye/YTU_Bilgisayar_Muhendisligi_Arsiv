    private void buttonApproveMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_buttonApproveMouseClicked
        int selectedRow = tableApprovedExpenses.getSelectedRow();
        
        if(selectedRow != -1) {
            int expenseId = (int) modelApprovedExpenses.getValueAt(selectedRow, 0);
            String process = cont.processExpensePayment(expenseId);
            
            if (process.equals("Tam ödeme yapıldı!")) {
                labelWarning.setForeground(new Color(102, 204, 0));
                comboBoxExpenseItem.setSelectedIndex(0);
            } else {
                labelWarning.setForeground(new Color(255, 0, 0));
            }

            labelWarning.setText(process);
            showApprovedExpenses();
        } else {
            labelWarning.setForeground(new Color(255, 0, 0));
            labelWarning.setText("Harcama seçiniz!");
        }
    }//GEN-LAST:event_buttonApproveMouseClicked

