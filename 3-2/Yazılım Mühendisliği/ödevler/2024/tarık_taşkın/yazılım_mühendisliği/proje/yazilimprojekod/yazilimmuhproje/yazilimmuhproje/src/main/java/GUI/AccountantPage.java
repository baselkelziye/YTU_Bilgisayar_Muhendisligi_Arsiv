    public void showApprovedExpenses() {
        modelApprovedExpenses.setRowCount(0);
        
        List<Expense> expenses = cont.getApprovedExpensesByDepartmentID(user.getDepartmentId());
        DateTimeFormatter formatter = DateTimeFormatter.ofPattern("dd MMM yyyy HH:mm");
        
        for(Expense expense: expenses){
            Object[] e ={expense.getId(), expense.getUserId(), expense.getExpenseItemId(), expense.getAmount(), expense.getStatus(), expense.getCreatedAt().format(formatter),
            expense.getDocumentPath()};
            modelApprovedExpenses.addRow(e);
        }
        
    }

