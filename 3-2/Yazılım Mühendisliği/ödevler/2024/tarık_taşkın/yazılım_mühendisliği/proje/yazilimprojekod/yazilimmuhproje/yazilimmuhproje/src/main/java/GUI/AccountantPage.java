    private void tableApprovedExpensesMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tableApprovedExpensesMouseClicked
        // TODO add your handling code here:
        int selectedRow = tableApprovedExpenses.getSelectedRow();
        
        if(selectedRow != -1) {
            int expenseItemId = Integer.parseInt(modelApprovedExpenses.getValueAt(selectedRow, 2).toString());
            comboBoxExpenseItem.setSelectedIndex(expenseItemId);
        }
    }//GEN-LAST:event_tableApprovedExpensesMouseClicked

    private void buttonCorrectExpenseItemMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_buttonCorrectExpenseItemMouseClicked
        // TODO add your handling code here:
        int selectedRow = tableApprovedExpenses.getSelectedRow();
        int newExpenseItemId = comboBoxExpenseItem.getSelectedIndex();
        
        if(selectedRow != -1 && newExpenseItemId > 0) {
            int expenseId = Integer.parseInt(modelApprovedExpenses.getValueAt(selectedRow, 0).toString());
            int expenseItemId = Integer.parseInt(modelApprovedExpenses.getValueAt(selectedRow, 2).toString());
            
            
            if (expenseItemId != newExpenseItemId) {
                cont.correctExpenseItem(expenseId, newExpenseItemId);
                
                labelWarning.setForeground(new Color(102, 204, 0));
                labelWarning.setText("Harcama kalemi düzeltildi!");
                comboBoxExpenseItem.setSelectedIndex(0);
                showApprovedExpenses();
            } else {
                labelWarning.setForeground(new Color(255, 0, 0));
                labelWarning.setText("Yeni kalem seçiniz!");
            }
        } else if (selectedRow == -1) {
            labelWarning.setForeground(new Color(255, 0, 0));
            labelWarning.setText("Harcama seçiniz!");
        } else {
            labelWarning.setForeground(new Color(255, 0, 0));
            labelWarning.setText("Yeni kalem seçiniz!");
        }
    }//GEN-LAST:event_buttonCorrectExpenseItemMouseClicked


