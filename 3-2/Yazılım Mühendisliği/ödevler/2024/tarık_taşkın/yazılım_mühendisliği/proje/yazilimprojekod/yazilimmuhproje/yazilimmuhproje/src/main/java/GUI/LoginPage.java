    private void buttonLoginMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_buttonLoginMouseClicked
        // TODO add your handling code here:
        String email = textLoginEmail.getText();
        String password = new String(textLoginPassword.getPassword());
        
        if (email.equals("") || email.equals("E-mail")) {
            labelWarning.setText("E-mail giriniz!");
            return;
        } else if (password.equals("") || textLoginPassword.getText().equals("jPasswordField1")) {
            labelWarning.setText("Şifre giriniz!");
            return;
        }
        
        UserDto user = cont.login(email, password);
        if (user == null) {
            labelWarning.setText("Hatalı Giriş!");
            return;
        } else if (user.getRole().equals("personel")) {
            PersonnelPage personalPage = new PersonnelPage(conn, user, this);
            personalPage.setVisible(true);
            this.setVisible(false);
        } else if (user.getRole().equals("muhasebe")) {
            AccountantPage accountantPage = new AccountantPage(conn, user, this);
            accountantPage.setVisible(true);
            this.setVisible(false);
        } else if (user.getRole().equals("yönetici")) {
            ManagerPage managerPage = new ManagerPage(conn, user, this);
            managerPage.setVisible(true);
            this.setVisible(false);
        } else if (user.getRole().equals("üst yönetim")) {
            SupervisorPage supervisorPage = new SupervisorPage(conn, user, this);
            supervisorPage.setVisible(true);
            this.setVisible(false);
        }          

        labelWarning.setText("");        
    }//GEN-LAST:event_buttonLoginMouseClicked

