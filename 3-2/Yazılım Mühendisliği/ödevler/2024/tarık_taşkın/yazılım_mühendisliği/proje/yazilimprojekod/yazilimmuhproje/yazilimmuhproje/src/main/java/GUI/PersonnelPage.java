    private void buttonAddExpenseMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_buttonAddExpenseMouseClicked
        // TODO add your handling code here:
        String text = textFieldAmount.getText();
        int expenseId = comboBoxExpenseItem.getSelectedIndex();
        int amount = 0;
        
        try {
            amount = Integer.parseInt(text);
        } catch (NumberFormatException e) {
            labelWarning.setForeground(new Color(255, 0, 0));
            labelWarning.setText("Geçerli miktar giriniz!");
            return;
        }
        
        if (expenseId == 0) {
            labelWarning.setForeground(new Color(255, 0, 0));
            labelWarning.setText("Harcama kalemi seçiniz!");
            return;
        }
        
        if (amount <= 0) {
            labelWarning.setForeground(new Color(255, 0, 0));
            labelWarning.setText("Geçerli miktar giriniz!");
            return;
        }        
        
        if (fileName == null) {
            labelWarning.setForeground(new Color(255, 0, 0));
            labelWarning.setText("Dosya seçiniz!");
            return;
        }
        
        cont.addExpense(user.getId(), expenseId, amount, fileName);
        System.out.println(text + " " + expenseId);
        
        labelWarning.setForeground(new Color(102, 204, 0));
        labelWarning.setText("Kayıt başarılı!");
        
        fileName = null;
        labelFile.setText("Dosya Seç");        
    }//GEN-LAST:event_buttonAddExpenseMouseClicked

