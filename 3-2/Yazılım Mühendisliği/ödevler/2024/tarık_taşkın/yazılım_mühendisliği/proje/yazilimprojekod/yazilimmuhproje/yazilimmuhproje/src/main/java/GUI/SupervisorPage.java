    public void showExpenseItems() {
        modelExpenseItems.setRowCount(0);
        
        List<ExpenseItem> expenseItems = itemCont.getExpenseItems();
        
        for(ExpenseItem e: expenseItems){
            Object[] expenseItem = {e.getId(), e.getName(), e.getDepartment_id(), e.getBudget(), e.getMaxLimit(), e.getUsedBudget()};
            modelExpenseItems.addRow(expenseItem);
        }        
    }
    
    public void showExpenseReports() {
        modelExpenseReports.setRowCount(0);
        
        List<ExpenseReportDto> expenseReports = serv.getGroupedExpenseReports();
        
        for(ExpenseReportDto e: expenseReports){
            Object[] expense = {e.getUserId(), e.getDepartmentId(), e.getExpenseItemId(), e.getMonthYear(), e.getTotalAmount()};
            modelExpenseReports.addRow(expense);
        }        
    }
    
    public void showBudgetEstimates(int period) {
        modelBudgetEstimates.setRowCount(0);
        
        Map<Integer, Double> estimates = cont.showDepartmentWiseBudgetEstimates(period);
        
        double total = 0;
        for (Map.Entry<Integer, Double> entry : estimates.entrySet()) {
            Object[] estimate = {entry.getKey(), entry.getValue()};
            total += entry.getValue();
            modelBudgetEstimates.addRow(estimate);
        }
        
        labelWarning.setForeground(new Color(102, 204, 0));
        labelWarning.setText("Toplam tahmini bütçe: %.2f TL".formatted(total));
    }

