    private void tabbedPaneStateChanged(javax.swing.event.ChangeEvent evt) {//GEN-FIRST:event_tabbedPaneStateChanged
        int selectedIndex = tabbedPane.getSelectedIndex();
        
        if (selectedIndex == 0) {
            textFieldBudget.setVisible(true);
            buttonUpdateBudget.setVisible(true);
            
            textFieldPeriod.setVisible(false);
            buttonEstimate.setVisible(false);
        } else if (selectedIndex == 1) {
            textFieldBudget.setVisible(false);
            buttonUpdateBudget.setVisible(false);
            
            textFieldPeriod.setVisible(false);
            buttonEstimate.setVisible(false);
        } else if (selectedIndex == 2) {
            textFieldPeriod.setVisible(true);
            buttonEstimate.setVisible(true);
            
            textFieldBudget.setVisible(false);
            buttonUpdateBudget.setVisible(false);
        }
        
        labelWarning.setText("");
    }//GEN-LAST:event_tabbedPaneStateChanged

