    private void buttonUpdateBudgetMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_buttonUpdateBudgetMouseClicked
        int selectedRow = tableExpenseItems.getSelectedRow();
        
        if (selectedRow == -1) {
            labelWarning.setForeground(new Color(255, 0, 0));
            labelWarning.setText("Harcama kalemi seçiniz!");
            return;
        } 
        
        int expenseItemId = (int) modelExpenseItems.getValueAt(selectedRow, 0);
        double budget = Double.parseDouble(modelExpenseItems.getValueAt(selectedRow, 3).toString());
        double newBudget = 0;
        
        try {
            newBudget = Double.parseDouble(textFieldBudget.getText());
        } catch (NumberFormatException e) {
            labelWarning.setForeground(new Color(255, 0, 0));
            labelWarning.setText("Geçerli miktar giriniz!");
            return;
        }
        
        if (newBudget < 0) {
            labelWarning.setForeground(new Color(255, 0, 0));
            labelWarning.setText("Geçerli miktar giriniz!");
            return;
        }
        
        if (newBudget == budget) {
            labelWarning.setForeground(new Color(255, 0, 0));
            labelWarning.setText("Yeni bütçe giriniz!");
            return;
        }
        
        itemCont.updateExpenseItemBudget(expenseItemId, newBudget);
        showExpenseItems();
        labelWarning.setForeground(new Color(102, 204, 0));
        labelWarning.setText("Bütçe güncellendi!");
    }//GEN-LAST:event_buttonUpdateBudgetMouseClicked

    private void buttonEstimateMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_buttonEstimateMouseClicked
        int period = 0;
        
        try {
            period = Integer.parseInt(textFieldPeriod.getText());
        } catch (NumberFormatException e) {
            labelWarning.setForeground(new Color(255, 0, 0));
            labelWarning.setText("Geçerli periyot giriniz!");
            return;
        }
        
        if (period <= 0) {
            labelWarning.setForeground(new Color(255, 0, 0));
            labelWarning.setText("Geçerli periyot giriniz!");
            return;
        }
        
        showBudgetEstimates(period);
    }//GEN-LAST:event_buttonEstimateMouseClicked

